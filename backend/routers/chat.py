@router.post("/chat")
def chat(message: str, thread_id: str = "default"):
    print(f"\n[BACKEND] [CHAT] /chat received (thread: {thread_id}): {message}", flush=True)
    result = graph.invoke({
        "messages": [HumanMessage(content=message)]
    }, config={
        "configurable": {
            "thread_id": thread_id
        }
    })

    # Retrieve final message content
    last_msg = result["messages"][-1]
    final_response = last_msg.content if isinstance(last_msg.content, str) else str(last_msg.content)
    cleaned = clean_response_text(final_response)
    print(f"[BACKEND] [CHAT] /chat finished response (length: {len(cleaned)} chars)", flush=True)

    return {
        "thread_id": thread_id,
        "response": cleaned
    }


@router.post("/chat/stream")
def chat_stream(
    message: Optional[str] = None, 
    thread_id: str = "default",
    resume_approved: Optional[bool] = None,
    resume_feedback: Optional[str] = None
):
    """
    Streaming endpoint returning real-time response tokens using Server-Sent Events (SSE).
    Handles normal messages, live thoughts, and resuming paused Human-in-the-Loop approval requests.
    """
    print(f"\n[BACKEND] [STREAM] started (thread: {thread_id}) | resume_approved={resume_approved}", flush=True)

    def event_generator():
        token_count = 0
        last_tool_id = None

        # 1. Determine input (Normal message VS Resume Command)
        if resume_approved is not None:
            stream_input = Command(resume={
                "approved": resume_approved,
                "feedback": (resume_feedback or "").strip()
            })
        else:
            if not message:
                yield f"data: {json.dumps({'content': 'No message provided.'})}\n\n"
                return
            stream_input = {"messages": [HumanMessage(content=message)]}

        for update in graph.stream(
            stream_input,
            config={"configurable": {"thread_id": thread_id}},
            stream_mode="updates"
        ):
            # 🛑 Check for Human Approval Interrupt
            if "__interrupt__" in update:
                interrupt_list = update["__interrupt__"]
                if interrupt_list:
                    interrupt_val = interrupt_list[0].value
                    print(f"[BACKEND] [HITL] 🛡️ Approval requested: {interrupt_val}", flush=True)
                    yield f"data: {json.dumps({'type': 'approval_required', 'data': interrupt_val})}\n\n"
                    return # Graph pauses right here!

            if "planner" in update:
                p_data = update["planner"]
                plan_steps = p_data.get("plan", [])
                if plan_steps:
                    label = f"Architect: Created {len(plan_steps)}-step execution plan"
                    print(f"[BACKEND] [THOUGHT] {label}", flush=True)
                    yield f"data: {json.dumps({'type': 'thought', 'id': 'plan_step', 'tool': 'search_codebase', 'status': 'done', 'label': label})}\n\n"

            if "coder" in update or "chatbot" in update:
                cb_data = update.get("coder") or update.get("chatbot")
                msgs = cb_data.get("messages", [])
                if msgs:
                    last_msg = msgs[-1]
                    # Check if this node execution was a tool call
                    tool_calls = getattr(last_msg, "tool_calls", None) or extract_tool_calls(last_msg)
                    if tool_calls:
                        for call in tool_calls:
                            c_dict = call if isinstance(call, dict) else {
                                "name": getattr(call, "name", ""),
                                "args": getattr(call, "args", {}),
                                "id": getattr(call, "id", None)
                            }
                            t_name = c_dict.get("name", "tool")
                            t_args = c_dict.get("args", {})
                            t_id = c_dict.get("id") or f"call_{uuid.uuid4().hex[:6]}"
                            last_tool_id = t_id

                            # Format friendly human-readable label
                            if t_name == "search_codebase":
                                q = t_args.get("query", "")
                                label = f'Searching codebase for "{q}"' if q else "Searching codebase & documents"
                            elif t_name == "read_file":
                                fp = t_args.get("file_path", "")
                                basename = os.path.basename(fp) if fp else "file"
                                label = f'Reading file: {basename}'
                            elif t_name == "write_file":
                                fp = t_args.get("file_path", "")
                                basename = os.path.basename(fp) if fp else "file"
                                label = f'Writing code to: {basename}'
                            elif t_name == "edit_file":
                                fp = t_args.get("file_path", "")
                                basename = os.path.basename(fp) if fp else "file"
                                label = f'Patching code in: {basename}'
                            elif t_name == "run_terminal_command":
                                cmd = t_args.get("command", "")
                                label = f'Executing terminal command: "{cmd}"'
                            elif t_name == "list_directory":
                                dp = t_args.get("directory_path", ".")
                                label = f'Listing files in: {dp}'
                            elif t_name == "execute_python_code":
                                label = "Executing Python code test"
                            elif t_name in ("get_memory", "list_memories"):
                                label = "Searching long-term memory"
                            elif t_name == "save_memory":
                                k = t_args.get("key", "")
                                label = f'Saving memory: "{k}"'
                            else:
                                label = f"Running {t_name}"

                            print(f"[BACKEND] [THOUGHT] Running tool {t_name}: {label}", flush=True)
                            yield f"data: {json.dumps({'type': 'thought', 'id': t_id, 'tool': t_name, 'status': 'running', 'label': label})}\n\n"

                    elif last_msg.content:
                        # Clean any tool tags or JSON artifacts
                        cleaned = clean_response_text(last_msg.content)
                        
                        # Stream words with smooth pacing
                        tokens = re.findall(r'\S+|\s+', cleaned)
                        for token in tokens:
                            token_count += 1
                            yield f"data: {json.dumps({'type': 'content', 'content': token})}\n\n"
                            time.sleep(0.012)

            elif "tools" in update:
                t_msgs = update["tools"].get("messages", [])
                for tm in t_msgs:
                    tm_id = getattr(tm, "tool_call_id", None) or getattr(tm, "id", None) or last_tool_id or f"done_{uuid.uuid4().hex[:6]}"
                    tm_name = getattr(tm, "name", "tool")
                    raw_content = getattr(tm, "content", "")
                    content_str = str(raw_content).strip()

                    # Format friendly completion summary
                    if tm_name == "search_codebase":
                        lines = [l for l in content_str.split("\n") if l.startswith("--- File:")]
                        summary = f"Found {len(lines)} matching snippet(s)" if lines else "Search completed"
                    elif tm_name == "read_file":
                        line_count = len(content_str.splitlines())
                        summary = f"Read {line_count} lines" if "Error" not in content_str else "File read failed"
                    elif tm_name == "write_file":
                        if "REJECTED" in content_str:
                            summary = "File write rejected by user"
                        elif "Successfully" in content_str:
                            summary = "File written successfully"
                        else:
                            summary = "File write finished"
                    elif tm_name == "edit_file":
                        if "REJECTED" in content_str:
                            summary = "File patch rejected by user"
                        elif "Successfully" in content_str:
                            summary = "File patched successfully"
                        else:
                            summary = "File patch finished"
                    elif tm_name == "run_terminal_command":
                        if "REJECTED" in content_str:
                            summary = "Terminal command rejected by user"
                        elif "Exit Code: 0" in content_str:
                            summary = "Terminal command executed successfully"
                        elif "AUTONOMOUS SELF-DEBUGGING TRIGGER" in content_str or "Exit Code:" in content_str:
                            summary = "Command failed — initiating autonomous self-debugging"
                        else:
                            summary = "Terminal command finished"
                    elif tm_name == "execute_python_code":
                        if "AUTONOMOUS SELF-DEBUGGING TRIGGER" in content_str or "FAILED" in content_str:
                            summary = "Python error detected — initiating autonomous self-debugging"
                        elif "STDOUT" in content_str or "successfully" in content_str:
                            summary = "Code executed successfully"
                        else:
                            summary = "Execution finished"
                    elif tm_name in ("save_memory", "get_memory", "list_memories"):
                        summary = "Memory query completed"
                    else:
                        summary = f"{tm_name} finished"

                    print(f"[BACKEND] [THOUGHT] Tool done {tm_name}: {summary}", flush=True)
                    yield f"data: {json.dumps({'type': 'thought', 'id': tm_id, 'tool': tm_name, 'status': 'done', 'label': summary})}\n\n"

            elif "reviewer" in update:
                r_data = update["reviewer"]
                status = r_data.get("review_status", "approved")
                if status == "rejected":
                    label = "QA Reviewer: ❌ Code issue detected — sent back to Coder to fix"
                    print(f"[BACKEND] [THOUGHT] {label}", flush=True)
                    yield f"data: {json.dumps({'type': 'thought', 'id': f'rev_{uuid.uuid4().hex[:6]}', 'tool': 'execute_python_code', 'status': 'running', 'label': label})}\n\n"
                else:
                    curr_step = r_data.get("current_step", 1)
                    task_name = r_data.get("completed_task") or f"Step {curr_step}"
                    label = f"QA Reviewer: ✅ Verified: {task_name}"
                    print(f"[BACKEND] [THOUGHT] {label}", flush=True)
                    yield f"data: {json.dumps({'type': 'thought', 'id': f'rev_{uuid.uuid4().hex[:6]}', 'tool': 'execute_python_code', 'status': 'done', 'label': label})}\n\n"

            elif "memory_extractor" in update:
                mem_data = update.get("memory_extractor", {})
                if mem_data.get("memory_updated") and mem_data.get("saved_count", 0) > 0:
                    count = mem_data.get("saved_count", 1)
                    label = f"Updated long-term memory ({count} new fact{'s' if count > 1 else ''})"
                    print(f"[BACKEND] [THOUGHT] {label}", flush=True)
                    yield f"data: {json.dumps({'type': 'thought', 'id': 'mem_extract', 'tool': 'save_memory', 'status': 'done', 'label': label})}\n\n"

        print(f"[BACKEND] [STREAM] /chat/stream finished (streamed ~{token_count} tokens)\n", flush=True)

    return StreamingResponse(event_generator(), media_type="text/event-stream")



@router.get("/chat/history/{thread_id}")
def chat_history(thread_id: str):

    history = list(graph.get_state_history(
        {"configurable": {"thread_id": thread_id}}
    ))

    if not history:
        return []

    latest_state = history[0].values
    messages = latest_state.get("messages", [])

    formatted = []
    for msg in messages:
        if isinstance(msg, HumanMessage):
            formatted.append({"type": "human", "content": msg.content})
        elif isinstance(msg, AIMessage):
            if not getattr(msg, "tool_calls", None) and not extract_tool_calls(msg):
                clean_txt = clean_response_text(msg.content)
                if clean_txt:
                    formatted.append({"type": "ai", "content": clean_txt})

    return [{"messages": formatted}]


@router.get("/chat/threads")
def get_threads():
    """
    Fetch all saved conversation thread IDs from checkpoints table in PostgreSQL,
    ordered by their most recent activity (latest checkpoint first).
    """
    import psycopg
    from psycopg.rows import dict_row
    from config.settings import DB_URI
    try:
        with psycopg.connect(DB_URI, row_factory=dict_row) as conn:
            with conn.cursor() as cur:
                cur.execute("""
                    SELECT thread_id, MAX(checkpoint_id) as last_cp 
                    FROM checkpoints 
                    WHERE thread_id NOT LIKE 'test_%' AND thread_id NOT LIKE 'verification_%'
                    GROUP BY thread_id 
                    ORDER BY last_cp DESC;
                """)
                rows = cur.fetchall()
                threads = [r["thread_id"] for r in rows if r.get("thread_id")]
                return {"threads": threads if threads else ["default"]}
    except Exception as e:
        return {"threads": ["default"], "error": str(e)}


@router.post("/ingest/files")
async def ingest_files(files: List[UploadFile] = File(...)):
    """
    Dynamically upload code and PDF files, extract text/chunks, embed via Ollama, and store in pgvector.
    """
    import io
    import pypdf

    documents = []

    for uploaded_file in files:
        try:
            raw_bytes = await uploaded_file.read()
            filename = uploaded_file.filename or "unknown"

            if filename.lower().endswith(".pdf"):
                try:
                    pdf_reader = pypdf.PdfReader(io.BytesIO(raw_bytes))
                    pages_text = []
                    for page_num, page in enumerate(pdf_reader.pages):
                        text = page.extract_text()
                        if text and text.strip():
                            pages_text.append(f"--- [Page {page_num + 1} of {filename}] ---\n{text.strip()}")
                    
                    content = "\n\n".join(pages_text)
                    if not content.strip():
                        content = f"[Empty or scanned PDF file: {filename}]"
                    print(f"[BACKEND] 📄 Extracted {len(pages_text)} page(s) from PDF: {filename}", flush=True)
                except Exception as pdf_err:
                    print(f"Error parsing PDF {filename}: {pdf_err}", flush=True)
                    content = f"Error extracting text from PDF {filename}: {str(pdf_err)}"
            else:
                try:
                    content = raw_bytes.decode("utf-8")
                except UnicodeDecodeError:
                    content = raw_bytes.decode("latin-1", errors="replace")

            documents.append(
                Document(
                    page_content=content,
                    metadata={"file_path": filename}
                )
            )
        except Exception as e:
            print(f"Error reading uploaded file {uploaded_file.filename}: {e}", flush=True)

    if not documents:
        return {"message": "No valid documents provided", "chunk_count": 0}

    # Split documents into chunks
    text_splitter = RecursiveCharacterTextSplitter(chunk_size=1000, chunk_overlap=200)
    chunks = text_splitter.split_documents(documents)

    # Ingest into pgvector
    vector_db.add_documents(chunks)

    return {
        "message": f"Successfully ingested {len(files)} file(s)",
        "chunk_count": len(chunks)
    }


from pydantic import BaseModel

class TitleRequest(BaseModel):
    message: str = ""


@router.post("/chat/title")
async def generate_chat_title(req: TitleRequest):
    """
    Generate a concise, 3-5 word ChatGPT-style topic title based on the conversation text.
    """
    message = req.message.strip()
    if not message:
        return {"title": "New Chat"}

    # Fast clean fallback
    words = [w for w in message.replace("\n", " ").split(" ") if w]
    clean_words = []
    stop_words = {"please", "can", "you", "tell", "me", "how", "to", "what", "is", "explain"}
    for w in words:
        if w.lower() not in stop_words or len(clean_words) > 0:
            clean_words.append(w)
        if len(clean_words) >= 4:
            break
    
    fallback_words = clean_words if clean_words else words[:4]
    fallback_title = " ".join(fallback_words)
    if len(fallback_title) > 32:
        fallback_title = fallback_title[:29] + "..."
    fallback_title = fallback_title.capitalize()

    try:
        from config.settings import llm
        prompt = (
            "Generate a very short, clean topic title (maximum 3 to 5 words, no quotation marks, no punctuation at end) "
            "for this conversation message:\n\n"
            f"Message: {message[:250]}\n\n"
            "Title:"
        )
        response = await llm.ainvoke(prompt)
        title = response.content.strip().strip('"\'*#`')
        title = title.split("\n")[0].strip()
        if len(title) > 35:
            title = title[:32] + "..."
        return {"title": title if title else fallback_title}
    except Exception as e:
        print(f"[BACKEND] Title generation fallback: {e}", flush=True)
        return {"title": fallback_title}



def clean_response_text(text: str) -> str:
    """
    Remove internal tool tags and JSON artifacts generated by local Ollama models.
    """
    if not isinstance(text, str):
        return str(text)

    # 1. If entire text is wrapped in a JSON block like {"response": "..."}
    trimmed = text.strip()
    json_candidate = None
    if trimmed.startswith("```"):
        m = re.search(r'```(?:json)?\s*(\{[\s\S]*?\})\s*```', trimmed)
        if m:
            json_candidate = m.group(1).strip()
    elif trimmed.startswith("{") and trimmed.endswith("}"):
        json_candidate = trimmed

    if json_candidate:
        try:
            parsed = json.loads(json_candidate)
            if isinstance(parsed, dict):
                for k in ["response", "message", "reply", "answer", "content"]:
                    if k in parsed and isinstance(parsed[k], str) and parsed[k].strip():
                        return parsed[k].strip()
        except Exception:
            pass

    # Strip <tool_response>...</tool_response> blocks
    cleaned = re.sub(r'<tool_response>[\s\S]*?</tool_response>', '', text, flags=re.IGNORECASE).strip()
    # Strip <tool_call>...</tool_call> blocks
    cleaned = re.sub(r'<tool_call>[\s\S]*?</tool_call>', '', cleaned, flags=re.IGNORECASE).strip()
    # Strip raw JSON markdown blocks
    cleaned = re.sub(r'```(?:json)?\s*\{[\s\S]*?\}\s*```', '', cleaned).strip()
    # Strip inline JSON objects
    cleaned = re.sub(r'\{\s*"name"\s*:\s*"[^"]+".*?\}\s*\}?', '', cleaned).strip()
    # Strip any remaining stray tool tags
    cleaned = re.sub(r'</?(?:tool_response|tool_call|tools?)>', '', cleaned, flags=re.IGNORECASE).strip()
    
    return cleaned if cleaned else text


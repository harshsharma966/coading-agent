from typing import Annotated
from pydantic import BaseModel
from langchain_core.messages import AnyMessage
from langgraph.graph.message import add_messages


class MyState(BaseModel):
    """
    State schema for the LangGraph Multi-Agent Team.
    - messages: conversation history (auto-merged via add_messages reducer)
    - response: latest AI response text
    - debug_retries: counter for autonomous self-debugging attempts
    - plan: list of discrete task steps generated by Planner
    - current_step: index of the active step being implemented
    - review_status: verdict from Reviewer ('pending', 'approved', 'rejected')
    - review_feedback: detailed suggestions/bugs reported by Reviewer
    """
    messages: Annotated[list[AnyMessage], add_messages]
    response: str = ""
    debug_retries: int = 0
    plan: list[str] = []
    current_step: int = 0
    review_status: str = "pending"
    review_feedback: str = ""
    completed_task: str = ""
    memory_updated: bool = False
    saved_count: int = 0


